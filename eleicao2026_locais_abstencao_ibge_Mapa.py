def urnas_do_turno(turno):
    el = eleitorado_turno(turno)
    v = (votos_pres[votos_pres["NR_TURNO"] == turno].rename(columns={"NR_SECAO": "NR_SECAO_URNA"})
         .pivot_table(index=CHAVE_URNA, columns="NM_VOTAVEL", values="QT_VOTOS", aggfunc="sum", fill_value=0))
    lula, flavio = coluna_candidato(v.columns, PADRAO_LULA), coluna_candidato(v.columns, PADRAO_FLAVIO)
    bn = [c for c in BRANCO_NULO if c in v]
    votos = pd.DataFrame({"LULA": v[lula], "FLAVIO": v[flavio],
                          "OUTROS": v.drop(columns=[lula, flavio, *bn]).sum(axis=1),
                          "BRANCO_NULO": v[bn].sum(axis=1), "COMPARECIMENTO": v.sum(axis=1)}).reset_index()
    t = (base_urnas(el).merge(votos, on=CHAVE_URNA, how="left", validate="one_to_one")
         .merge(cadastro_locais(el)[CHAVE_LOCAL + [c for c in DADOS_LOCAL if c in el]],
                on=CHAVE_LOCAL, how="left", validate="many_to_one"))
    num = ["LULA", "FLAVIO", "OUTROS", "BRANCO_NULO", "COMPARECIMENTO"]
    t[num] = t[num].fillna(0).astype("int64")
    t["ABSTENCAO"] = t["APTOS"] - t["COMPARECIMENTO"]
    return t


def distancia_m(lat1, lon1, lat2, lon2):
    lat1, lon1, lat2, lon2 = (np.radians(x.astype(float)) for x in (lat1, lon1, lat2, lon2))
    a = np.sin((lat2 - lat1) / 2) ** 2 + np.cos(lat1) * np.cos(lat2) * np.sin((lon2 - lon1) / 2) ** 2
    return 2 * 6_371_000 * np.arcsin(np.sqrt(a))


