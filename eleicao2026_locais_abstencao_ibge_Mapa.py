def indicadores(d):
    for t in ("T1", "T2"):
        dois = (d[f"LULA_{t}"] + d[f"FLAVIO_{t}"]).where(lambda s: s > 0)
        d[f"PCT_LULA_2C_{t}"] = (100 * d[f"LULA_{t}"] / dois).round(2)
        d[f"PCT_ABST_{t}"] = (100 * d[f"ABSTENCAO_{t}"] / d[f"APTOS_{t}"].where(lambda s: s > 0)).round(2)
        d[f"LIDER_{t}"] = np.select([d[f"LULA_{t}"] > d[f"FLAVIO_{t}"], d[f"LULA_{t}"] < d[f"FLAVIO_{t}"]],
                                    ["LULA", "FLAVIO"], "EMPATE")
    d["DELTA_LULA_2C_PP"] = (d["PCT_LULA_2C_T2"] - d["PCT_LULA_2C_T1"]).round(2)
    d["DELTA_ABST_PP"] = (d["PCT_ABST_T2"] - d["PCT_ABST_T1"]).round(2)
    d["DELTA_VOTOS_LULA"] = d["LULA_T2"] - d["LULA_T1"]
    d["DELTA_VOTOS_FLAVIO"] = d["FLAVIO_T2"] - d["FLAVIO_T1"]
    d["DELTA_ABSTENCAO"] = d["ABSTENCAO_T2"] - d["ABSTENCAO_T1"]
    d["VIROU"] = d["LIDER_T1"] != d["LIDER_T2"]
    return d


