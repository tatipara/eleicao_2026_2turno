def coluna_candidato(colunas, padrao):
    achados = [c for c in colunas if re.search(padrao, c)]
    assert len(achados) == 1, f"o padrão {padrao} encontrou {achados}; ajuste PADRAO_LULA / PADRAO_FLAVIO"
